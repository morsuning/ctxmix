// Package ctxmix is a pure-Go, dependency-free, maximum-ratio general purpose
// compressor based on context mixing, the technique behind the PAQ, lpaq and
// ZPAQ family of archivers.
//
// It trades speed for size: on Go source code its output is about 27% smaller
// than "xz -9e" and about 3.5% smaller than ZPAQ's strongest built-in model (zpaq -m5), but
// compression and decompression run at roughly 0.2 to 0.5 MB/s per core, several
// times slower than xz, and each in-flight block needs about 100 MiB of model
// memory (see [MemoryUsage]). Decompression costs the same as compression,
// because the decoder runs the same model. Use it where bytes matter more than
// seconds: release artifacts, backups, incremental sync bundles. Do not use it
// for latency-sensitive paths or for data that is already compressed.
//
// The output is a ctxmix stream in a format of its own (see FORMAT.md in the
// repository). It is NOT a ZPAQ archive and cannot be read by zpaq; for ZPAQ
// compatibility use github.com/morsuning/zpaq-go.
//
// # Usage
//
// The streaming API mirrors compress/flate:
//
//	w, err := ctxmix.NewWriter(dst)            // or NewWriter(dst, ctxmix.WithConcurrency(4))
//	if err != nil { ... }
//	w.Write(data)
//	w.Close()                                  // required: flushes the last block
//
//	r, err := ctxmix.NewReader(src)
//	if err != nil { ... }
//	io.Copy(out, r)
//
// For in-memory data use [EncodeAll] and [DecodeAll]. [Inspect] reports the
// structure of a stream without decompressing it. Callers that build their own
// container format can use the headerless [EncodeBlock] and [DecodeBlock].
//
// # Format and versioning
//
// A stream is a sequence of independent blocks (16 MiB of input by default),
// each with its own length and CRC-32, followed by an end marker, so blocks can
// be compressed and decompressed in parallel (see [WithConcurrency]). The output
// does not depend on the concurrency setting. Every stream starts with a magic
// number that carries the format version. Until v1.0.0 the format may change in
// a minor release, always with a new version byte so that old readers fail
// loudly; the test suite pins the compressed bytes of several inputs to catch
// accidental changes.
//
// # Determinism
//
// The model uses integer arithmetic only, with all lookup tables embedded as
// constants or generated by integer code, so compressed output is bit-identical
// on every architecture and operating system (CI covers amd64, arm64, 32-bit x86
// and big-endian s390x).
//
// # Safety
//
// Decoding is defensive: malformed input yields [ErrCorrupt] (or
// io.ErrUnexpectedEOF), never a panic or an out-of-bounds access; every block is
// verified against its CRC-32, and the framing is strict (canonical varints,
// exact payload lengths). A tiny crafted stream can still expand to a lot of
// data, as with any decompressor: when decoding untrusted input set
// [WithMaxBlockSize] and [WithMaxOutputSize], and use [WithContext] for a
// deadline.
